package com.lordsai.lsi.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.OneToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.LocalDate;

@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "student_profiles", indexes = {
        @Index(name = "idx_student_profiles_student_id", columnList = "student_id", unique = true)
})
public class StudentProfile extends BaseEntity {

    @OneToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false, unique = true)
    private User user;

    /**
     * Human-facing identifier, e.g. LSI-2026-00001. Generated by the academy, never changed by the
     * student. An Automation Admin student's ebook login keeps their academy Student ID (LSA/...),
     * so the two series never clash.
     */
    @Column(name = "student_id", nullable = false, length = 30)
    private String studentId;

    /**
     * A login made by the Automation Admin for an academy (office) student: the Student Panel shows
     * only the ebook while the account has no course.
     */
    @Column(name = "academy_ebook_only", nullable = false)
    private boolean academyEbookOnly;

    /**
     * The User ID the student signs in to the Student Portal with — separate from the Student ID (the
     * record reference). Generated for every new student (e.g. "rahul4821"); students from before the
     * split kept their Student ID text (V34). The student can change it in Settings.
     */
    @Column(name = "login_id", length = 40, unique = true)
    private String loginId;

    @Column(length = 100)
    private String batch;

    @Column(length = 150)
    private String location;

    @Column(name = "profile_photo_path", length = 255)
    private String profilePhotoPath;

    @Column(name = "registration_date", nullable = false)
    private LocalDate registrationDate;

    /** The ID the student signs in with. (Falls back to the Student ID text only for a legacy row not yet backfilled.) */
    public String userId() {
        return loginId != null ? loginId : studentId;
    }
}
